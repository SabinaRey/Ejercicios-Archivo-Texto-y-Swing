    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        int id =
                Integer.parseInt(txtId.getText());
        Producto existente =
                archivo.buscar(id);
        // SI YA EXISTE
        if (existente != null) {
            JOptionPane.showMessageDialog(
                    this,
                    "El producto ya existe");
            
            for (int i = 0;
                    i < tblDatos.getRowCount();
                    i++) {
                int idTabla =
                        Integer.parseInt(
                                tblDatos.getValueAt(i, 0)
                                        .toString());
                if (idTabla == id) {
                    filaEncontrada = i;
                    tblDatos.setRowSelectionInterval(
                            i,
                            i);
                    tblDatos.scrollRectToVisible(
                            tblDatos.getCellRect(
                                    i,
                                    0,
                                    true));
                    break;
                }
            }
            tblDatos.repaint();
            return;
        }
        // AGREGAR NUEVO
        Producto p = new Producto(
                id,
                txtNombre.getText(),
                txtDescripcion.getText(),
                Integer.parseInt(
                        txtExistencia.getText())
        );
        archivo.agregarProducto(p);
        cargarTabla();
        limpiarCampos();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int id =
                Integer.parseInt(txtId.getText());
        if (archivo.eliminar(id)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Eliminado");
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "No encontrado");
        }
        cargarTabla();
        limpiarCampos();
        filaEncontrada = -1;
        tblDatos.repaint();
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        int fila =
                tblDatos.getSelectedRow();

        // MODIFICAR DESDE TABLA
        if (fila >= 0) {
            int id = Integer.parseInt(
                    tblDatos.getValueAt(fila, 0)
                            .toString());
            String nombre = tblDatos.getValueAt(fila, 1).toString();
            String descripcion = tblDatos.getValueAt(fila, 2).toString();

            int existencia = Integer.parseInt(tblDatos.getValueAt(fila, 3).toString());
            boolean ok = archivo.modificar(
                    id,
                    nombre,
                    descripcion,
                    existencia);
            JOptionPane.showMessageDialog(
                    this,
                    ok
                    ? "Modificado desde tabla"
                    : "No encontrado");
            cargarTabla();
            filaEncontrada = -1;
            tblDatos.repaint();
        }
        // MODIFICAR DESDE TEXTBOX
        else {
            int id =
                    Integer.parseInt(
                            txtId.getText());
            boolean ok = archivo.modificar(
                    id,
                    txtNombre.getText(),
                    txtDescripcion.getText(),
                    Integer.parseInt(
                            txtExistencia.getText())
            );
            JOptionPane.showMessageDialog(
                    this,
                    ok
                    ? "Modificado"
                    : "No encontrado");
            cargarTabla();
            limpiarCampos();
            filaEncontrada = -1;
            tblDatos.repaint();
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        String idBuscar =txtId.getText();
        if (idBuscar.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No puedes dejar campos vacíos");
            txtId.requestFocus();
        } else {
            int id =
                    Integer.parseInt(idBuscar);
            Producto p =
                    archivo.buscar(id);
            if (p != null) {
                txtNombre.setText(p.getNombre());
                txtDescripcion.setText(p.getDescripcion());
                txtExistencia.setText(String.valueOf(p.getExistencia()));
                habilitarDeshabilitarElimModif(true);
                // BUSCAR FILA
                for (int i = 0;i < tblDatos.getRowCount();i++) {
                    int idTabla =Integer.parseInt(tblDatos.getValueAt(i, 0).toString());

                    if (idTabla == p.getId()) {
                        filaEncontrada = i;
                        tblDatos.setRowSelectionInterval(
                                i,
                                i);
                        tblDatos.scrollRectToVisible(
                                tblDatos.getCellRect(
                                        i,
                                        0,
                                        true));
                        break;
                    }
                }
                tblDatos.repaint();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "No encontrado");
            }
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

