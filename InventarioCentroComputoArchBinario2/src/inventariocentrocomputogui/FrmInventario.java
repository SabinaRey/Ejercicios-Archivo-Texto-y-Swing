    public FrmInventario() {
        initComponents();
        modelo = new DefaultTableModel() {

            @Override
            public boolean isCellEditable(int row, int column) {
                // NO PERMITE EDITAR EL ID
                return column != 0;
            }
        };
        modelo.addColumn("ID");
        modelo.addColumn("Nombre");
        modelo.addColumn("Descripción");
        modelo.addColumn("Existencia");
        tblDatos.setModel(modelo);
        cargarTabla();
        txtId.requestFocus();

        habilitarDeshabilitarElimModif(false);
        // SELECCIONAR FILA
        tblDatos.getSelectionModel().addListSelectionListener(e -> {
            int fila = tblDatos.getSelectedRow();
            if (fila >= 0) {
                txtId.setText(tblDatos.getValueAt(fila, 0).toString());
                txtNombre.setText(tblDatos.getValueAt(fila, 1).toString());
                txtDescripcion.setText(tblDatos.getValueAt(fila, 2).toString());
                txtExistencia.setText(tblDatos.getValueAt(fila, 3).toString());
                habilitarDeshabilitarElimModif(true);
            }
        });

        // PINTAR FILAS
        tblDatos.setDefaultRenderer(
                Object.class,
                new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(
                    JTable table,
                    Object value,
                    boolean isSelected,
                    boolean hasFocus,
                    int row,
                    int column) {
                Component c =
                        super.getTableCellRendererComponent(
                                table,
                                value,
                                isSelected,
                                hasFocus,
                                row,
                                column);

                // FILA SELECCIONADA
                if (isSelected) {
                    c.setBackground(Color.CYAN);
                }
                // FILA ENCONTRADA
                else if (row == filaEncontrada) {
                    c.setBackground(Color.YELLOW);
                }
                // NORMAL
                else {
                    c.setBackground(Color.WHITE);
                }
                return c;
            }
        });
    }

    private void habilitarDeshabilitarElimModif(
            boolean estado) {
        btnEliminar.setEnabled(estado);
        btnModificar.setEnabled(estado);
    }
  
   private void limpiarTabla() {
        modelo.setRowCount(0);
    }

    private void limpiarCampos() {
        txtId.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");
        txtExistencia.setText("");
        txtId.requestFocus();
        habilitarDeshabilitarElimModif(false);
    }

    private void cargarTabla() {
        limpiarTabla();
        ArrayList<Producto> lista =
                archivo.leerTodos();
        
        for (Producto p : lista) {
            if (p.isEstado()) {
                modelo.addRow(new Object[]{
                    p.getId(),
                    p.getNombre(),
                    p.getDescripcion(),
                    p.getExistencia()
                });
            }
        }
    }

